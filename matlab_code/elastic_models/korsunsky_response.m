function modulus = korsunsky_response(depthRatio, parameters)
% Korsunsky and Constantinescu (2009), Eq. 4.
% parameters: shallow and deep asymptotes (GPa), beta0, eta.
if ~isnumeric(depthRatio) || ~isreal(depthRatio) || isempty(depthRatio) || ...
        any(~isfinite(depthRatio(:)) | depthRatio(:) < 0) || ...
        ~isnumeric(parameters) || ~isreal(parameters) || numel(parameters) ~= 4 || ...
        any(~isfinite(parameters(:)) | parameters(:) <= 0)
    error('NIMS:Korsunsky:InvalidInput', ...
        'Depth ratios must be finite and nonnegative; all four parameters must be finite and positive.');
end
weight = (1 - tanh(parameters(4) .* ...
    (log(depthRatio) - log(parameters(3))) ./ 2)) ./ 2;
modulus = parameters(2) + (parameters(1) - parameters(2)) .* weight;
end
